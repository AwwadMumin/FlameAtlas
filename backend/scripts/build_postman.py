"""Generate docs/postman_collection.json from the live OpenAPI schema + demo scenarios (variable {{baseUrl}})."""
import json
import os

os.environ["MOCK"] = "1"
from app.core.config import get_settings  # noqa: E402
from app.main import app  # noqa: E402

DOCS = get_settings().docs_dir
SAMPLE = {"q": "acrylic", "material_id": "pmma", "experiment_id": "WSTF-013", "preset": "iss"}


def item(method, path, body=None, params=None):
    url = "{{baseUrl}}" + "".join(f"/{SAMPLE.get(x[1:-1], x)}" if x.startswith("{") else f"/{x}" for x in path.strip("/").split("/"))
    q = [{"key": k, "value": SAMPLE.get(k, "")} for k in (params or [])]
    it = {"name": f"{method.upper()} {path}", "request": {"method": method.upper(), "header": [{"key": "Content-Type", "value": "application/json"}],
          "url": {"raw": url + ("?" + "&".join(f"{x['key']}={x['value']}" for x in q) if q else ""), "host": ["{{baseUrl}}"],
                  "path": [p for p in url.replace("{{baseUrl}}", "").strip("/").split("/")], "query": q}}}
    if body is not None:
        it["request"]["body"] = {"mode": "raw", "raw": json.dumps(body, indent=2, ensure_ascii=False), "options": {"raw": {"language": "json"}}}
    return it


spec = app.openapi()
scen = json.loads((DOCS / "examples" / "demo_scenarios.json").read_text())["scenarios"]
items = []
for path, ops in spec["paths"].items():
    for method, op in ops.items():
        params = [p["name"] for p in op.get("parameters", []) if p["in"] == "query" and p.get("required")]
        if path == "/api/assess":
            for s in scen:
                it = item(method, path, s["request"]); it["name"] = f"POST /api/assess — {s['title']}"; items.append(it)
        elif path == "/api/admin/labels":
            items.append(item(method, path, {"experiment_id": "BASS-001", "label": "unclear", "quote": "<copy a span from flame_behavior_notes>", "labelled_by": "your-name"}))
        else:
            items.append(item(method, path, params=params))
col = {"info": {"name": "Mission Lens API", "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
                "description": "Generated by backend/scripts/build_postman.py from /openapi.json"},
       "variable": [{"key": "baseUrl", "value": "http://localhost:8000"}], "item": sorted(items, key=lambda i: i["name"])}
(DOCS / "postman_collection.json").write_text(json.dumps(col, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
print("wrote postman_collection.json with", len(items), "requests")
