"""Generate docs/PROVENANCE.md from the data files (counts, sources, DOIs, licenses). Run: python scripts/build_provenance.py"""
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.core.config import get_settings  # noqa: E402

D = get_settings().data_dir
from app.services import extra_sources  # noqa: E402

base_n = len(json.loads((D / "experiments.json").read_text(encoding="utf-8")))
exps = json.loads((D / "experiments.json").read_text(encoding="utf-8")) + extra_sources.extras(D)
meta = json.loads((D / "materials.json").read_text(encoding="utf-8"))["metadata"]
K = json.loads((D / "flame_in_freefall_knowledge.json").read_text(encoding="utf-8"))
inv = {i["accession"]: i for i in K["investigations"]}

by = defaultdict(list)
for e in exps:
    by[e["source_investigation"]].append(e)
L = ["# Data provenance", "", "Generated by `backend/scripts/build_provenance.py` from `data/*.json` (read-only inputs).", "",
     f"- Dataset version `{meta['version']}`, built {meta['built']}: {meta['n_materials']} materials, {meta['n_experiments']} experiments, {meta['records_without_material']} without a material.",
     f"- Builder note: {meta['note']}",
     f"- Loaded data set = {base_n} base records + {len(exps) - base_n} records from extra sources (Link et al. 2018 supplementary Tables S1/S2, CC BY 4.0, attribution required) = {len(exps)}.", "", "| Source | Records | With outcome | Conditions only | DOI / link | License | Source rows |", "|---|---|---|---|---|---|---|"]
for src, rs in sorted(by.items(), key=lambda kv: -len(kv[1])):
    dois = sorted({e["doi"] for e in rs if e["doi"]})
    link = ", ".join(f"[{d}](https://doi.org/{d})" for d in dois) or next((f"[NTRS]({e['source_file']})" for e in rs if (e["source_file"] or "").startswith("http")), "n/a")
    lic = ", ".join(sorted({e["license"] for e in rs if e["license"]}))
    outc = sum(e["outcome_type"] != "conditions_only" for e in rs)
    files = sorted({e["source_file"] for e in rs if e["source_file"] and not e["source_file"].startswith("http")})
    L.append(f"| {src} | {len(rs)} | {outc} | {len(rs) - outc} | {link} | {lic} | {'; '.join(files) or 'NTRS PDF tables'} |")
L += ["", "## Evidence types", "", "| evidence_type | records |", "|---|---|"] + [f"| {k} | {v} |" for k, v in Counter(e["evidence_type"] for e in exps).most_common()]
L += ["", "## Smoke / detection records (never shown as burn evidence)", "",
      f"{sum(e['flammability_relevant'] is False for e in exps)} records have `flammability_relevant = false` ({', '.join(sorted({e['source_investigation'] for e in exps if e['flammability_relevant'] is False}))}): heated, not burned.",
      "", "## Investigations (knowledge pack)", "", "| PSI | Acronym | Title | DOI |", "|---|---|---|---|"]
L += [f"| {i['accession']} | {i.get('acronym') or ''} | {i['title']} | {('[' + i['doi'] + '](https://doi.org/' + i['doi'] + ')') if i.get('doi') else ''} |" for i in K["investigations"]]
L += ["", "## Not from NASA data", "",
      "- Arabic names, aliases and `chemical_family` are search helpers written by the dataset builder, not NASA data.",
      "- The Van Krevelen 1g LOI correlation (17.5 + 0.40 x char yield) is an empirical formula supplied in the team brief, not a NASA measurement.",
      "- The Mars gravity value (0.38 g) is general knowledge; cite a NASA source if it is shown.",
      "- Link 2018 Tables S1/S2 (Scientific Reports 8:120, CC BY 4.0) are not loaded yet; the importer design keeps each source in its own file so they can be added later.",
      "- Crew-note outcome labels are human judgements stored in `data/derived/outcome_labels.json` with the supporting quote and labeller."]
(get_settings().docs_dir / "PROVENANCE.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote docs/PROVENANCE.md")
